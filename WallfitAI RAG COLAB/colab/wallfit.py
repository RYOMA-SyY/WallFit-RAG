def load_local_documents(root_dir):
    """Load trusted local files with PII masking."""
    documents = []
    if not os.path.exists(root_dir):
        print(f'ERROR: Directory not found: {root_dir}')
        return []

    print('--- Loading Local Documents ---')
    for dirpath, _, filenames in os.walk(root_dir):
        for filename in filenames:
            if not validate_source(filename):
                continue
            filepath = os.path.join(dirpath, filename)
            ext = filename.lower().split('.')[-1]
            try:
                if ext == 'pdf':
                    print(f'  [PDF] {filename}')
                    docs = PyPDFLoader(filepath).load()
                    for d in docs:
                        d.page_content = mask_sensitive_data(d.page_content)
                    documents.extend(docs)

                elif ext == 'docx':
                    print(f'  [DOCX] {filename}')
                    docs = Docx2txtLoader(filepath).load()
                    for d in docs:
                        d.page_content = mask_sensitive_data(d.page_content)
                    documents.extend(docs)

                elif ext == 'csv':
                    print(f'  [CSV] {filename}')
                    df = pd.read_csv(filepath, nrows=2000)
                    masked = mask_sensitive_data(df.to_string(index=False))
                    documents.append(Document(page_content=masked, metadata={'source': filepath}))

            except Exception as e:
                print(f'  [SKIP] {filename}: {e}')

    print(f'Local documents loaded: {len(documents)}')
    return documents


