def validate_source(filename):
    """Only allow ingestion from a whitelist of trusted files."""
    if filename not in TRUSTED_SOURCES:
        print(f'  [BLOCKED] Untrusted source: {filename}')
        return False
    return True


def mask_sensitive_data(text):
    """Anonymize PII and secrets before embedding."""
    text = re.sub(r'\b[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Z|a-z]{2,}\b', '[EMAIL]', text)
    text = re.sub(r'\b\d{3}[-.\s]??\d{3}[-.\s]??\d{4}\b', '[PHONE]', text)
    text = re.sub(r'(?i)(api[_-]?key|secret|password|passwd|token|auth)[:=]\s*[\w-]{16,}', r'\1:[MASKED]', text)
    text = re.sub(r'\b\d{4}[-\s]?\d{4}[-\s]?\d{4}[-\s]?\d{4}\b', '[CARD]', text)
    return text


