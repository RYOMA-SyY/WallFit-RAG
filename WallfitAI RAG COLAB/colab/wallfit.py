# -----------------------------------------------------------------
# Document Scoring
# -----------------------------------------------------------------

def score_and_filter_docs(query, vector_db, k=5, threshold=1.5):
    """Retrieve documents with L2 distance scoring. Lower is better."""
    results = vector_db.similarity_search_with_score(query, k=k)
    filtered = [(doc, score) for doc, score in results if score <= threshold]

    if not filtered:
        return "No relevant context found in the knowledge base.", []

    context_parts = []
    sources = []
    for doc, score in filtered:
        src = doc.metadata.get('source', 'unknown')
        src_label = os.path.basename(src) if '/' in src or '\\' in src else src
        context_parts.append(f"[Source: {src_label} | Score: {score:.2f}]\n{doc.page_content}")
        sources.append(src_label)

    return "\n\n".join(context_parts), sources


