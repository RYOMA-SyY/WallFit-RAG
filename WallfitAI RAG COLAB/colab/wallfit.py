def build_vector_db(dataset_dir, hf_datasets, db_dir):
    """Build Chroma vector store from local files + HuggingFace datasets."""
    if os.path.exists(db_dir):
        shutil.rmtree(db_dir)
        print('Cleared old database.')

    # Load from both sources
    local_docs = load_local_documents(dataset_dir)
    hf_docs = load_hf_datasets(hf_datasets)
    all_docs = local_docs + hf_docs

    if not all_docs:
        print('ERROR: No documents loaded from any source.')
        return None

    print(f'\nTotal documents combined: {len(all_docs)}')

    print('Splitting into chunks...')
    splitter = RecursiveCharacterTextSplitter(chunk_size=1000, chunk_overlap=200)
    chunks = splitter.split_documents(all_docs)
    print(f'  -> {len(chunks)} chunks created.')

    print('Computing embeddings...')
    embeddings = HuggingFaceEmbeddings(model_name=EMBED_MODEL)

    print('Building vector store...')
    vector_db = Chroma.from_documents(
        documents=chunks,
        embedding=embeddings,
        persist_directory=db_dir
    )
    print(f'Vector database ready. Chunks indexed: {vector_db._collection.count()}')
    return vector_db

