# -----------------------------------------------------------------
# Main Query Function
# -----------------------------------------------------------------

def ask_wallfit(query, vector_db):
    """Full secure pipeline: Sanitize -> Retrieve -> Score -> Generate."""

    # Layer 1: Input sanitization
    try:
        clean_query = sanitize_query(query)
    except SecurityError as e:
        return f'[BLOCKED] {e}'

    # Layer 2: Document retrieval with scoring
    context, sources = score_and_filter_docs(clean_query, vector_db)

    # Layer 3: Build prompt with Qwen chat format
    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": f"CONTEXT:\n{context[:4000]}\n\nQUESTION: {clean_query}"}
    ]

    formatted_prompt = tokenizer.apply_chat_template(
        messages,
        tokenize=False,
        add_generation_prompt=True
    )

    response = llm.invoke(formatted_prompt)

    if sources:
        response += f"\n\n[Sources: {', '.join(set(sources))}]"

    return response.strip()

