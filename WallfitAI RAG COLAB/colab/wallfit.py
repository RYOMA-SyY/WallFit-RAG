def load_hf_datasets(dataset_ids, max_rows=3000):
    """Download and convert HuggingFace datasets into LangChain Documents."""
    documents = []
    print('\n--- Loading HuggingFace Datasets ---')

    for ds_id in dataset_ids:
        print(f'  [HF] {ds_id}...')
        try:
            ds = load_dataset(ds_id, split='train')
            columns = ds.column_names
            count = 0

            for row in ds:
                if count >= max_rows:
                    break

                # Build text from all available fields
                parts = []
                for col in columns:
                    val = row.get(col)
                    if val and isinstance(val, str) and len(val.strip()) > 0:
                        parts.append(f"{col}: {val.strip()}")

                text = "\n".join(parts)
                if len(text) > 20:  # skip empty/trivial rows
                    masked = mask_sensitive_data(text)
                    documents.append(Document(
                        page_content=masked,
                        metadata={'source': ds_id, 'type': 'hf_dataset'}
                    ))
                    count += 1

            print(f'       -> {count} entries loaded.')

        except Exception as e:
            print(f'       -> ERROR: {e}')

    print(f'HuggingFace documents loaded: {len(documents)}')
    return documents



